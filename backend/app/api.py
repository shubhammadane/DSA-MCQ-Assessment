        db.query(models.Department).filter(models.Department.id.in_(deleted_ids)).delete(synchronize_session=False)
        db.commit()
        log_deletion_audit(admin.username, "BULK_PERMANENT_DELETE", "department", deleted_ids, "SUCCESS")
