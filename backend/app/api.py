@router.post("/admin/backup/verify")
def verify_system_backup(
    data: Dict[str, str],
    admin: CurrentUser = Depends(require_super_admin)
):
    import hashlib
    filename = data.get("filename", "")
    if not filename or filename != os.path.basename(filename) or not filename.endswith(".json"):
        raise HTTPException(status_code=400, detail="Invalid backup filename.")
    index_path = os.path.join(BACKUP_DIR, "index.json")
    allowed_files = set()
    if os.path.exists(index_path):
        try:
            with open(index_path, "r", encoding="utf-8") as index_file:
                for entry in json.load(index_file):
                    if isinstance(entry, dict) and entry.get("filename"):
                        allowed_files.add(entry["filename"])
        except (OSError, ValueError, TypeError):
            raise HTTPException(status_code=500, detail="Backup index is invalid.")
    if filename not in allowed_files:
        raise HTTPException(status_code=404, detail="Backup is not registered in the backup index.")
    backup_path = os.path.join(BACKUP_DIR, filename)
    if not os.path.exists(backup_path):
        raise HTTPException(status_code=404, detail="Backup file not found.")

    with open(backup_path, "r", encoding="utf-8") as f:
        content = f.read()

    try:
        parsed = json.loads(content)
        calc_hash = hashlib.sha256(content.encode("utf-8")).hexdigest()
        meta = parsed.get("metadata", {})
        return {
            "status": "verified",
            "filename": filename,
            "calculated_sha256": calc_hash,
            "recorded_total_records": meta.get("total_records", 0),
            "table_counts": meta.get("table_counts", {}),
            "created_at": meta.get("created_at")
        }
    except Exception as e:
        logger.exception("Backup verification failed")
        raise HTTPException(status_code=400, detail="The backup file is invalid or could not be verified.")

