def calculate_attempt_score(attempt: models.Attempt, db: Session):
    """Recalculate score and percentage for an attempt based on actual questions."""
    db.flush()
    answer = models.StudentAnswer
    marks = case((answer.marks > 0, answer.marks), else_=1)
    total, correct_count, available_marks, earned_marks = db.query(
        func.count(answer.id),
        func.coalesce(func.sum(case((answer.is_correct == True, 1), else_=0)), 0),
        func.coalesce(func.sum(marks), 1),
        func.coalesce(func.sum(case((answer.is_correct == True, marks), else_=0)), 0),
    ).filter(answer.attempt_id == attempt.id).one()
    
    attempt.correct_answers = correct_count
    attempt.wrong_answers = total - correct_count
    attempt.score = earned_marks
    attempt.percentage = round((earned_marks / available_marks) * 100.0, 2)


def _session_code_hash(code: str) -> str:
    return hmac.new(settings.SECRET_KEY.encode(), code.strip().encode(), hashlib.sha256).hexdigest()


def _generate_session_code() -> str:
    # Eight random digits, including leading zeroes, generated by the OS CSPRNG.
    return f"{secrets.randbelow(100_000_000):08d}"


def _verify_session_code(exam: models.Exam, code: str) -> bool:
    if not exam.session_code_hash:
        return False
    return hmac.compare_digest(exam.session_code_hash, _session_code_hash(code))


def _parse_exam_datetime(date_value: Optional[str], time_value: Optional[str], field_name: str) -> Optional[datetime]:
    if not date_value:
        return None
    try:
        local_value = datetime.strptime(
            f"{date_value} {time_value or ('23:59' if field_name == 'end' else '00:00')}",
            "%Y-%m-%d %H:%M",
        ).replace(tzinfo=ZoneInfo(settings.EXAM_TIMEZONE))
    except (ValueError, TypeError) as exc:
        raise HTTPException(
            status_code=400,
            detail=f"Invalid {field_name} date/time. Use YYYY-MM-DD and HH:MM.",
        ) from exc
    return local_value.astimezone(ZoneInfo("UTC")).replace(tzinfo=None)


def _validate_exam_window(start_date: Optional[str], start_time: Optional[str], end_date: Optional[str], end_time: Optional[str]):
    start_at = _parse_exam_datetime(start_date, start_time, "start")
    end_at = _parse_exam_datetime(end_date, end_time, "end")
    if start_at and end_at and end_at <= start_at:
        raise HTTPException(status_code=400, detail="Exam end date/time must be later than its start date/time.")
    return start_at, end_at


