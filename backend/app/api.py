    target_subj_id = exam_in.subject_id if exam_in.subject_id is not None else exam.subject_id
    target_selection_mode = exam_in.selection_mode if exam_in.selection_mode is not None else exam.selection_mode
    target_question_count = exam_in.total_questions if exam_in.total_questions is not None else exam.total_questions
    if exam_in.title is not None:
        if not exam_in.title.strip():
            raise HTTPException(status_code=400, detail="Exam title is required.")
        exam.title = exam_in.title.strip()
    if "code" in exam_in.model_fields_set:
        exam.code = exam_in.code.strip() if exam_in.code else None

    # Validate department update if requested (Super Admin only)
    if exam_in.department_id is not None and not admin.is_hod:
        dept = db.query(models.Department).filter(models.Department.id == exam_in.department_id).first()
        if not dept:
            raise HTTPException(status_code=400, detail="Selected department not found.")
        exam.department_id = dept.id
        exam.department_name = dept.name

    # Validate subject update if requested
    if exam_in.subject_id is not None:
        subj = db.query(models.Subject).filter(models.Subject.id == exam_in.subject_id).first()
        if not subj:
            raise HTTPException(status_code=400, detail="Selected subject not found.")
        if not subj.is_active:
            raise HTTPException(status_code=400, detail="Selected subject is inactive.")
        if target_dept_id and subj.department_id != target_dept_id:
            raise HTTPException(status_code=400, detail="Selected subject does not belong to the selected department.")
        exam.subject_id = subj.id
        exam.subject_name = subj.name
    elif exam_in.department_id is not None and exam.subject_id:
        # Check that existing subject matches the new department
        subj = db.query(models.Subject).filter(models.Subject.id == exam.subject_id).first()
        if subj and target_dept_id and subj.department_id != target_dept_id:
            raise HTTPException(
                status_code=400,
                detail="Existing subject does not belong to the newly selected department. Please update the subject association."
            )
    if exam_in.program_id is not None:
        prog = db.query(models.Program).filter(models.Program.id == exam_in.program_id).first()
        if not prog or not prog.is_active:
            raise HTTPException(status_code=400, detail="Selected program does not exist or is inactive.")
        exam.program_id = prog.id
        exam.program_name = prog.name
    if exam_in.academic_year_id is not None:
        ay = db.query(models.AcademicYear).filter(models.AcademicYear.id == exam_in.academic_year_id).first()
        if not ay or not ay.is_active:
            raise HTTPException(status_code=400, detail="Selected academic year does not exist or is inactive.")
        exam.academic_year_id = ay.id
        exam.year_name = ay.name
    if exam_in.semester_id is not None:
        sem = db.query(models.Semester).filter(models.Semester.id == exam_in.semester_id).first()
        if not sem or not sem.is_active:
            raise HTTPException(status_code=400, detail="Selected semester does not exist or is inactive.")
        exam.semester_id = sem.id
        exam.semester_name = sem.name
    if exam.academic_year_id:
        year = db.get(models.AcademicYear, exam.academic_year_id)
        if exam.program_id and year.program_id != exam.program_id:
            raise HTTPException(status_code=400, detail="Selected academic year does not belong to the selected program.")
    if exam.semester_id:
        semester = db.get(models.Semester, exam.semester_id)
        if (exam.academic_year_id and semester.academic_year_id != exam.academic_year_id) or (exam.program_id and semester.program_id != exam.program_id):
            raise HTTPException(status_code=400, detail="Selected semester does not belong to the selected program and year.")
    if "start_date" in exam_in.model_fields_set:
        exam.start_date = exam_in.start_date
    if "start_time" in exam_in.model_fields_set:
        exam.start_time = exam_in.start_time
    if "end_date" in exam_in.model_fields_set:
        exam.end_date = exam_in.end_date
    if "end_time" in exam_in.model_fields_set:
        exam.end_time = exam_in.end_time
    if exam_in.duration_minutes is not None:
        exam.duration_minutes = exam_in.duration_minutes
    if exam_in.total_questions is not None:
        exam.total_questions = exam_in.total_questions
    if exam_in.marks_per_question is not None:
        exam.marks_per_question = exam_in.marks_per_question
    if exam_in.total_marks is not None:
        exam.total_marks = exam_in.total_marks
    if exam_in.passing_percentage is not None:
        exam.passing_percentage = exam_in.passing_percentage
    if exam_in.selection_mode is not None:
        exam.selection_mode = exam_in.selection_mode
    if exam_in.status is not None:
        exam.status = exam_in.status
    if exam_in.is_active is not None:
        exam.is_active = exam_in.is_active
    if exam_in.result_release_mode is not None:
        exam.result_release_mode = exam_in.result_release_mode
    exam.total_marks = exam.total_questions * exam.marks_per_question

    if target_selection_mode == "random":
        question_query = db.query(models.Question).filter(models.Question.is_active == True)
        if target_subj_id:
            question_query = question_query.filter(models.Question.subject_id == target_subj_id)
        elif target_dept_id:
            question_query = question_query.filter(models.Question.department_id == target_dept_id)
        if question_query.count() < target_question_count:
            raise HTTPException(status_code=400, detail="The selected question bank does not contain enough active questions.")

    if target_selection_mode == "manual":
        if exam_in.selected_question_ids is None:
            selected_ids = [row.question_id for row in exam.questions]
        else:
            selected_ids = exam_in.selected_question_ids
        expected_count = exam_in.total_questions if exam_in.total_questions is not None else exam.total_questions
        if len(selected_ids) != len(set(selected_ids)) or len(selected_ids) != expected_count:
            raise HTTPException(status_code=400, detail="Manual selection must contain unique IDs matching total_questions.")
        selected = db.query(models.Question).filter(models.Question.id.in_(selected_ids)).all()
        if len(selected) != len(selected_ids):
            raise HTTPException(status_code=400, detail="One or more selected questions do not exist.")
        invalid = [q.id for q in selected if not q.is_active or (target_subj_id and q.subject_id != target_subj_id) or (target_dept_id and q.department_id not in (None, target_dept_id))]
        if invalid:
            raise HTTPException(status_code=400, detail=f"Selected questions are inactive or outside the exam scope: {invalid}.")
        db.query(models.ExamQuestion).filter(models.ExamQuestion.exam_id == exam.id).delete()
        for idx, qid in enumerate(selected_ids, start=1):
            db.add(models.ExamQuestion(exam_id=exam.id, question_id=qid, order_index=idx))
    else:
        db.query(models.ExamQuestion).filter(models.ExamQuestion.exam_id == exam.id).delete()

    exam.updated_at = datetime.utcnow()
    db.commit()
    db.refresh(exam)

    assigned_cnt = db.query(models.ExamStudent).filter(models.ExamStudent.exam_id == exam.id).count()
    attempts_cnt = db.query(models.Attempt).filter(models.Attempt.exam_id == exam.id).count()
    e_dict = schemas.ExamOut.model_validate(exam)
    e_dict.assigned_students_count = assigned_cnt
    e_dict.attempts_count = attempts_cnt
    e_dict.has_session_code = bool(exam.session_code_hash)
    return e_dict


