@router.get("/attempts/{attempt_id}/result", response_model=schemas.TestResultOut)
def get_attempt_result(
    attempt_id: int,
    current_student: models.Student = Depends(get_current_student),
    db: Session = Depends(get_db),
):
    attempt = _owned_attempt(attempt_id, current_student, db, lock=True)
    if attempt.status == "in_progress":
        if attempt.deadline_at and datetime.utcnow() >= attempt.deadline_at:
            attempt.status = "timed_out"
            attempt.completed_at = attempt.deadline_at
            calculate_attempt_score(attempt, db)
            db.commit()
        else:
            raise HTTPException(status_code=409, detail="Submit the exam before viewing its result.")

    student = db.query(models.Student).filter(models.Student.id == attempt.student_id).first()
    student_answers = db.query(models.StudentAnswer).filter(
        models.StudentAnswer.attempt_id == attempt_id
    ).order_by(models.StudentAnswer.question_number.asc()).all()

    maximum_score = sum(max(1, answer.marks or 1) for answer in student_answers)
    review_available = True
    review_message = None
    if attempt.exam:
        _, exam_end_at = _validate_exam_window(
            attempt.exam.start_date,
            attempt.exam.start_time,
            attempt.exam.end_date,
            attempt.exam.end_time,
        )
        review_available = (
            attempt.exam.result_release_mode == "immediate"
            or attempt.exam.status in ("closed", "archived")
            or bool(exam_end_at and datetime.utcnow() > exam_end_at)
        )
        if not review_available:
            review_message = "Your score is recorded. Question review will be released after the examination closes."

    security_logs = db.query(models.ExamSecurityLog).filter(
        models.ExamSecurityLog.attempt_id == attempt_id
    ).order_by(models.ExamSecurityLog.occurred_at.asc()).all()

    answers_out = []
    for sa in student_answers if review_available else []:
        opts = {
            "A": sa.option_a or "",
            "B": sa.option_b or "",
            "C": sa.option_c or "",
            "D": sa.option_d or ""
        }
        if not any(opts.values()) and sa.question_number in QUESTIONS_BY_ID:
            opts = QUESTIONS_BY_ID[sa.question_number].get("options", {})

        q_text = sa.question_text
        if not q_text and sa.question_number in QUESTIONS_BY_ID:
            q_text = QUESTIONS_BY_ID[sa.question_number].get("question", "")

        answers_out.append({
            "question_number": sa.question_number,
            "question": q_text or f"Question {sa.question_number}",
            "options": opts,
            "selected_answer": sa.selected_answer,
            "correct_answer": sa.correct_answer,
            "marks": sa.marks or 1,
            "is_correct": sa.is_correct
        })

    # Release the connection before response serialization is scheduled.
    db.commit()
    return {
        "student": student,
        "attempt": attempt,
        "answers": answers_out,
        "security_logs": security_logs if review_available else [],
        "review_available": review_available,
        "review_message": review_message,
        "maximum_score": maximum_score,
    }


